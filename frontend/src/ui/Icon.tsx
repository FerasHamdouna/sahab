export const DROP_PATH = PATHS.drop;

export function conditionIcon(c: Condition, isDay: boolean): IconName {
  switch (c) {
    case 'clear': return isDay ? 'sun' : 'moon';
    case 'partly': return isDay ? 'cloudSun' : 'cloudMoon';
    case 'overcast': return 'cloud';
    default: return c;
  }
}
